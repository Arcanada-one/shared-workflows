#!/usr/bin/env bash
# Render a systemd drop-in that pins pnpm's content-addressable store to the
# runner's own _work tree. Multiple Runner.Listener units that share one OS
# user otherwise converge on ~/.local/share/pnpm/store/v11/index.db and can
# fail concurrent installs with [ERR_PNPM_ERR_SQLITE_ERROR] disk I/O error.
#
# Usage:
#   render-runner-pnpm-store-dropin.sh <absolute-runner-root>
#   render-runner-pnpm-store-dropin.sh --unit-name <systemd-unit> <absolute-runner-root>
#
# Prints the drop-in body to stdout. Does not write to /etc or restart units.
# Refuses relative roots, missing `$runner_root/_work`, `..` segments, and any
# character outside [A-Za-z0-9/._-] so Environment= cannot be line-injected.
set -euo pipefail

unit_name=""
if [[ "${1:-}" == "--unit-name" ]]; then
  unit_name="${2:-}"
  shift 2
fi

runner_root="${1:-}"
if [[ -z "$runner_root" ]]; then
  echo "usage: $0 [--unit-name UNIT] <absolute-runner-root>" >&2
  exit 2
fi
if [[ "$runner_root" != /* ]]; then
  echo "runner root must be absolute: $runner_root" >&2
  exit 2
fi
if [[ "$runner_root" == */ ]]; then
  runner_root="${runner_root%/}"
fi
# Fail closed on newline/control/space/= before any filesystem look-up so a
# crafted path cannot inject a second Environment= line into the drop-in.
if [[ "$runner_root" == *$'\n'* ]] || [[ "$runner_root" == *$'\r'* ]] \
  || [[ "$runner_root" == *$'\t'* ]] || [[ "$runner_root" == *' '* ]] \
  || [[ "$runner_root" == *'='* ]] || [[ "$runner_root" == *'"'* ]] \
  || [[ "$runner_root" == *"'"* ]] || [[ "$runner_root" == *'\\'* ]]; then
  echo "runner root contains disallowed characters (newline/control/space/=/quote): refuse" >&2
  exit 2
fi
case "$runner_root" in
  *..*)
    echo "runner root must not contain '..' segments: $runner_root" >&2
    exit 2
    ;;
esac
if [[ ! "$runner_root" =~ ^[A-Za-z0-9/._-]+$ ]]; then
  echo "runner root charset must be [A-Za-z0-9/._-]: refuse" >&2
  exit 2
fi
if [[ ! -d "${runner_root}/_work" ]]; then
  echo "runner root must contain an existing _work directory: ${runner_root}/_work" >&2
  exit 2
fi
if [[ -n "$unit_name" && "$unit_name" != *.service ]]; then
  echo "unit name must end with .service: $unit_name" >&2
  exit 2
fi

store_dir="${runner_root}/_work/_pnpm-store"

cat <<EOF
# Generated by shared-workflows scripts/render-runner-pnpm-store-dropin.sh
# Apply as:
#   /etc/systemd/system/<unit>.service.d/30-pnpm-store.conf
# then: systemctl daemon-reload && systemctl restart <unit>
# Do not use npm_config_store_dir for pnpm 11 — it is ignored; pnpm reads
# pnpm_config_store_dir (measured on pnpm 11.20.0).
[Service]
Environment=pnpm_config_store_dir=${store_dir}
EOF

if [[ -n "$unit_name" ]]; then
  echo "# target_unit=${unit_name}" >&2
fi
echo "# store_dir=${store_dir}" >&2
